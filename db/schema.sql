-- Zomato Lite schema
-- Two tables, linked by restaurant_id. See the PRD data model.

CREATE TABLE IF NOT EXISTS restaurant (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  location    text NOT NULL,
  cuisine     text NOT NULL,
  type        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz
);

CREATE TABLE IF NOT EXISTS review (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id  integer NOT NULL REFERENCES restaurant(id) ON DELETE CASCADE,
  rating         integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
  review         text NOT NULL CHECK (length(btrim(review)) > 0),
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz
);

-- Review list and latest-review lookups are always per restaurant, newest first.
CREATE INDEX IF NOT EXISTS review_restaurant_created_idx
  ON review (restaurant_id, created_at DESC, id DESC);
